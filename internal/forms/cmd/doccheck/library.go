package main

import (
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"

	"github.com/synodlang/compiler/internal/forms"
)

const libraryIndexHeader = "# Library examples\n\nGenerated by `doccheck -update`; do not edit.\n\n| Phrase | Examples |\n| --- | --- |\n"

// libraryFolder is the folder of a std package: "std/net" is net, and
// "std/look/basic" is lookbasic.
func libraryFolder(path string) string {
	return strings.ReplaceAll(strings.TrimPrefix(path, "std/"), "/", "")
}

// checkLibrary checks the runnable examples of the Library (decision 105):
// every example <package>/<name>/ passes fmt and check and runs (or fails with
// the code in its expect file), and every exported std phrase, events
// included, is used by an example of its package. It writes the index
// README.md with -update.
func checkLibrary(cfg *config, p *problems) {
	phrases, err := cfg.docs.phrases()
	if err != nil {
		p.add(cfg.synod, "%v", err)
		return
	}
	tmp, err := copyTo(cfg.library)
	if err != nil {
		p.add(cfg.library, "%v", err)
		return
	}
	defer os.RemoveAll(tmp)

	// used maps an exported pattern to the examples that use it.
	used := map[string][]string{}
	checked := map[string]bool{}
	for _, pkg := range cfg.stdPackages() {
		folder := libraryFolder(pkg)
		var examples []string
		entries, err := os.ReadDir(filepath.Join(cfg.library, folder))
		if err != nil {
			p.add(cfg.library, "no folder %s/ for %s", folder, pkg)
			continue
		}
		for _, e := range entries {
			if e.IsDir() && !strings.HasPrefix(e.Name(), ".") && len(synodFolders(filepath.Join(cfg.library, folder, e.Name()))) > 0 {
				examples = append(examples, folder+"/"+e.Name())
			}
		}
		exported := map[string]bool{}
		for _, ph := range phrases[pkg] {
			exported[ph.Pattern] = true
		}
		for _, ex := range examples {
			checked[ex] = true
			u := checkExample(cfg, p, tmp, ex)
			if u == nil {
				continue
			}
			for _, pat := range u.PhraseList() {
				if exported[pat] {
					used[pat] = append(used[pat], ex)
				}
			}
		}
		for _, ph := range phrases[pkg] {
			if len(used[ph.Pattern]) == 0 {
				p.add(filepath.Join(cfg.library, folder), "no example uses %s (%s %q)", pkg, ph.Kind, ph.Pattern)
			}
		}
	}
	dirs, _ := os.ReadDir(cfg.library)
	for _, d := range dirs {
		if !d.IsDir() || strings.HasPrefix(d.Name(), ".") {
			continue
		}
		known := false
		for _, pkg := range cfg.stdPackages() {
			known = known || libraryFolder(pkg) == d.Name()
		}
		if !known {
			p.add(filepath.Join(cfg.library, d.Name()), "is no std package folder")
		}
	}

	var b strings.Builder
	b.WriteString(libraryIndexHeader)
	for _, pkg := range cfg.stdPackages() {
		for _, ph := range phrases[pkg] {
			ex := used[ph.Pattern]
			if len(ex) == 0 {
				continue
			}
			sort.Strings(ex)
			names := make([]string, len(ex))
			for i, e := range ex {
				names[i] = "`" + e + "`"
			}
			fmt.Fprintf(&b, "| `%s` | %s |\n", ph.Pattern, strings.Join(names, ", "))
		}
	}
	index := filepath.Join(cfg.library, "README.md")
	have, err := os.ReadFile(index)
	switch {
	case err == nil && string(have) == b.String():
	case cfg.update:
		if err := os.WriteFile(index, []byte(b.String()), 0o644); err != nil {
			p.add(index, "%v", err)
		}
	case err != nil:
		p.add(index, "missing (run doccheck -update)")
	default:
		p.add(index, "stale (run doccheck -update)")
	}
}

var codeInRun = regexp.MustCompile(`error\[([a-z-]+)\]`)

// checkExample checks one example folder (a path relative to the library
// copy in tmp) and returns what it uses; nil when it is broken.
func checkExample(cfg *config, p *problems, tmp, ex string) *forms.Uses {
	where := filepath.Join(cfg.library, filepath.FromSlash(ex))
	if !lintFolder(cfg, p, where, tmp, ex) {
		return nil
	}
	want := ""
	if _, err := os.Stat(filepath.Join(where, "expect")); err == nil {
		code, err := readExpect(where)
		if err != nil {
			p.add(where, "%v", err)
			return nil
		}
		want = code
	}
	out, errOut, exit := runSynod(cfg.synod, tmp, "run", ex, "--summary", "--style", "short")
	switch {
	case want == "" && exit != 0:
		p.add(where, "synod run %s: exit %d (an example without an expect file must run)\n    %s", ex, exit, firstLines(out+errOut, 6))
		return nil
	case want != "":
		var got []string
		for _, m := range codeInRun.FindAllStringSubmatch(out+errOut, -1) {
			got = append(got, m[1])
		}
		if exit == 0 || len(got) == 0 || got[0] != want {
			p.add(where, "synod run %s should fail with %s, found exit %d and codes %v", ex, want, exit, got)
			return nil
		}
		for _, g := range got {
			if g != want {
				p.add(where, "synod run %s fails with %v, expected only %s", ex, got, want)
				return nil
			}
		}
	}
	u, diags, err := forms.AnalyzeDir(filepath.Join(tmp, filepath.FromSlash(ex)))
	if err != nil || u == nil {
		p.add(where, "usage analysis failed: %v %d diagnostics", err, len(diags))
		return nil
	}
	return u
}
