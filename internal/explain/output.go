package explain

import (
	"bytes"
	"encoding/json"
	"fmt"
	"io"
	"strings"

	"github.com/synodlang/compiler/internal/pipeline"
)

// Format name of `synod explain --json`.
const jsonFormat = "synod-explain/1"

// List writes one line per entry, "<code>  <summary>".
func List(w io.Writer, entries []*Entry) error {
	for _, e := range entries {
		if _, err := fmt.Fprintf(w, "%s  %s\n", e.Code, e.Summary); err != nil {
			return err
		}
	}
	return nil
}

// Text writes the explanation of one code (decision 93):
//
//	<code>: <summary>
//
//	<prose>
//
//	Example (p/p.synod):
//	    <file>
//	synod check says:
//	    <diagnostic>
//
//	Fix: <sentence>
//	    <fixed file>
//
// The rich form is the same with the diagnostic in its rich form; color adds
// bold to the code and the headings.
func Text(w io.Writer, d *Doc, st pipeline.Style) error {
	e := d.Entry
	bold := func(s string) string {
		if st.Color {
			return "\x1b[1m" + s + "\x1b[0m"
		}
		return s
	}
	var b strings.Builder
	fmt.Fprintf(&b, "%s %s\n\n%s\n", bold(e.Code+":"), e.Summary, e.Text)
	for _, f := range e.Example {
		fmt.Fprintf(&b, "\n%s\n", bold("Example ("+f.Path+"):"))
		indent(&b, f.Content)
	}
	fmt.Fprintf(&b, "\n%s\n", bold("synod "+e.Command()+" says:"))
	indent(&b, d.Diagnostic(st))
	fmt.Fprintf(&b, "\n%s %s\n", bold("Fix:"), e.FixNote)
	labels := len(e.FixFiles)+len(e.FixDeleted) > 1
	for _, f := range e.FixFiles {
		if labels {
			fmt.Fprintf(&b, "  %s:\n", f.Path)
		}
		indent(&b, f.Content)
	}
	for _, p := range e.FixDeleted {
		fmt.Fprintf(&b, "  %s (deleted)\n", p)
	}
	_, err := io.WriteString(w, b.String())
	return err
}

// indent writes s with each non-empty line indented by 4.
func indent(b *strings.Builder, s string) {
	for _, l := range strings.SplitAfter(strings.TrimSuffix(s, "\n"), "\n") {
		if strings.TrimRight(l, "\n") != "" {
			b.WriteString("    ")
		}
		b.WriteString(l)
	}
	b.WriteString("\n")
}

type jsonExample struct {
	Files   map[string]string `json:"files"`
	Program string            `json:"program"`
}

type jsonFix struct {
	Note    string            `json:"note"`
	Files   map[string]string `json:"files"`
	Deleted []string          `json:"deleted"`
}

type jsonCode struct {
	Code       string      `json:"code"`
	Kind       string      `json:"kind"`
	Summary    string      `json:"summary"`
	Text       string      `json:"text"`
	Command    string      `json:"command"`
	Example    jsonExample `json:"example"`
	Diagnostic string      `json:"diagnostic"`
	Fix        jsonFix     `json:"fix"`
}

type jsonDoc struct {
	Format string     `json:"format"`
	Codes  []jsonCode `json:"codes"`
}

// WriteJSON writes the synod-explain/1 document of docs: one compact line
// ending in a newline. The diagnostic is the short form lines.
func WriteJSON(w io.Writer, docs []*Doc) error {
	out := jsonDoc{Format: jsonFormat, Codes: []jsonCode{}}
	for _, d := range docs {
		e := d.Entry
		c := jsonCode{
			Code: e.Code, Kind: e.Kind(), Summary: e.Summary, Text: e.Text, Command: e.Command(),
			Example:    jsonExample{Files: map[string]string{}, Program: e.Program},
			Diagnostic: d.Diagnostic(pipeline.Style{}),
			Fix:        jsonFix{Note: e.FixNote, Files: map[string]string{}, Deleted: []string{}},
		}
		for _, f := range e.Example {
			c.Example.Files[f.Path] = f.Content
		}
		for _, f := range e.FixFiles {
			c.Fix.Files[f.Path] = f.Content
		}
		c.Fix.Deleted = append(c.Fix.Deleted, e.FixDeleted...)
		out.Codes = append(out.Codes, c)
	}
	var buf bytes.Buffer
	enc := json.NewEncoder(&buf)
	enc.SetEscapeHTML(false)
	if err := enc.Encode(out); err != nil {
		return err
	}
	_, err := w.Write(buf.Bytes())
	return err
}

// CatalogGenerated is the line under the title of the catalog.
const CatalogGenerated = "Generated by `synod explain --catalog`; do not edit."

// WriteCatalog writes the Markdown catalog: the title, the generated line and
// the table of codes with summary and fix note, in the order of spec/11.
func WriteCatalog(w io.Writer, entries []*Entry) error {
	var b strings.Builder
	b.WriteString("# Synod diagnostic codes\n\n" + CatalogGenerated + "\n\n| Code | Meaning | Fix |\n| --- | --- | --- |\n")
	for _, e := range entries {
		fmt.Fprintf(&b, "| `%s` | %s | %s |\n", e.Code, cell(e.Summary), cell(e.FixNote))
	}
	_, err := io.WriteString(w, b.String())
	return err
}

func cell(s string) string { return strings.ReplaceAll(s, "|", `\|`) }
