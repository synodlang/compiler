// Style says how the text form is written: rich is the terminal form, with
// a heading and a blank line between entries; color adds bold and dim.
type Style struct {
	Rich, Color bool
}

func (s Style) bold(t string) string {
	if s.Color {
		return "\x1b[1m" + t + "\x1b[0m"
	}
	return t
}

func (s Style) dim(t string) string {
	if s.Color {
		return "\x1b[2m" + t + "\x1b[0m"
	}
	return t
}

// kindText is the first word of the second line of an entry.
func (ph *Phrase) detail() string {
	var parts []string
	switch ph.Kind {
	case "node-event":
		parts = append(parts, "node event")
	case "trace-event":
		parts = append(parts, "trace event")
	default:
		if ph.Gives == Action {
			parts = append(parts, "action")
		} else {
			parts = append(parts, "gives "+ph.Gives)
		}
	}
	if ph.std {
		parts = append(parts, ph.ctx.String())
	}
	if ph.Doc != "" {
		parts = append(parts, ph.Doc)
	}
	return strings.Join(parts, "; ")
}

func fieldList(fs []Field) string {
	parts := make([]string, len(fs))
	for i, f := range fs {
		parts[i] = f.Name + " " + f.Type
	}
	return strings.Join(parts, ", ")
}

// fieldsLine is "<head>:" and the fields after a space, if there are any.
func fieldsLine(st Style, head string, fs []Field) string {
	if len(fs) == 0 {
		return st.bold(head)
	}
	return st.bold(head) + " " + st.dim(fieldList(fs))
}

// Write prints p in the short form, or in the rich form with a heading.
func Write(w io.Writer, p *Package, st Style) error {
	var b strings.Builder
	var entries [][]string // each entry: its lines, already styled
	for i := range p.Phrases {
		ph := &p.Phrases[i]
		entries = append(entries, []string{st.bold(ph.Pattern), st.dim("    " + ph.detail())})
	}
	for _, r := range p.Records {
		entries = append(entries, []string{fieldsLine(st, "record "+r.Name+":", r.Fields)})
	}
	if p.Node != nil {
		name := "Node"
		if p.Qualifier != "" {
			name = p.Qualifier + ".Node"
		}
		entries = append(entries, []string{fieldsLine(st, "node "+name+":", p.Node.Fields)})
	}
	if p.Activates {
		entries = append(entries, []string{fmt.Sprintf("importing activates %d observers, %d invariants", p.Observers, p.Invariants)})
	}
	if st.Rich {
		h := p.Path
		if p.Title != "" {
			h += " — " + p.Title
		}
		b.WriteString(st.bold(h))
		b.WriteString("\n")
		if len(entries) > 0 {
			b.WriteString("\n")
		}
	}
	for i, e := range entries {
		if st.Rich && i > 0 {
			b.WriteString("\n")
		}
		for _, l := range e {
			b.WriteString(l)
			b.WriteString("\n")
		}
	}
	_, err := io.WriteString(w, b.String())
	return err
}

// Scope is the "scope" key of the JSON document.
type Scope struct {
	File    string        `json:"file"`
	Package string        `json:"package"`
	Imports []ScopeImport `json:"imports"`
}

// ScopeImport is one import of the scope file.
type ScopeImport struct {
	Path      string `json:"path"`
	Qualifier string `json:"qualifier"`
}

type document struct {
	Format      string              `json:"format"`
	Diagnostics []source.Diagnostic `json:"diagnostics"`
	Scope       *Scope              `json:"scope"`
	Packages    []*Package          `json:"packages"`
}

// WriteJSON writes the synod-doc/1 document: one compact line.
func WriteJSON(w io.Writer, diags []source.Diagnostic, scope *Scope, pkgs []*Package) error {
	if diags == nil {
		diags = []source.Diagnostic{}
	}
	if pkgs == nil {
		pkgs = []*Package{}
	}
	var buf bytes.Buffer
	enc := json.NewEncoder(&buf)
	enc.SetEscapeHTML(false)
	if err := enc.Encode(document{Format: Format, Diagnostics: diags, Scope: scope, Packages: pkgs}); err != nil {
		return err
	}
	_, err := w.Write(buf.Bytes())
	return err
}

// Entry is one line of the package list.
type Entry struct {
	Path  string
	Title string
}

// WriteList prints the visible packages, one per line.
func WriteList(w io.Writer, es []Entry) error {
	var b strings.Builder
	for _, e := range es {
		b.WriteString(e.Path)
		if e.Title != "" {
			b.WriteString("  " + e.Title)
		}
		b.WriteString("\n")
	}
	_, err := io.WriteString(w, b.String())
	return err
}

// Catalog returns the std catalog as Markdown (synod doc --catalog). pkgs
// are the std packages built with their qualifiers; they are put in byte
// order of their paths.
func Catalog(pkgs []*Package) string {
	sorted := append([]*Package(nil), pkgs...)
	sort.Slice(sorted, func(i, j int) bool { return sorted[i].Path < sorted[j].Path })
	var b strings.Builder
	b.WriteString("# Synod standard library\n\n")
	b.WriteString("Generated by `synod doc --catalog` for Synod 0.2. Do not edit.\n")
	for _, p := range sorted {
		b.WriteString("\n## " + p.Path)
		if p.Title != "" {
			b.WriteString(" — " + p.Title)
		}
		b.WriteString("\n\n")
		var rows, nodeEv, traceEv []*Phrase
		var colors []*Phrase
		for i := range p.Phrases {
			ph := &p.Phrases[i]
			switch {
			case ph.Kind == "node-event":
				nodeEv = append(nodeEv, ph)
			case ph.Kind == "trace-event":
				traceEv = append(traceEv, ph)
			case p.colors[headOf(ph)] != "":
				colors = append(colors, ph)
			default:
				rows = append(rows, ph)
			}
		}
		empty := true
		if len(rows) > 0 {
			empty = false
			b.WriteString("| Phrase | Gives | Context | Meaning |\n| --- | --- | --- | --- |\n")
			for _, ph := range rows {
				fmt.Fprintf(&b, "| `%s` | %s | %s | %s |\n", ph.Pattern, markdownGives(ph.Gives), ph.ctx.String(), cell(ph.Doc))
			}
			b.WriteString("\n")
		}
		if len(colors) > 0 {
			empty = false
			b.WriteString("| Name | Value | Use |\n| --- | --- | --- |\n")
			for _, ph := range colors {
				fmt.Fprintf(&b, "| `%s` | `%s` | %s |\n", ph.Pattern, p.colors[headOf(ph)], cell(ph.Doc))
			}
			b.WriteString("\n")
		}
		if len(p.Records) > 0 {
			empty = false
			b.WriteString("Records:\n\n")
			for _, r := range p.Records {
				fmt.Fprintf(&b, "- `%s`: %s\n", r.Name, fieldList(r.Fields))
			}
			b.WriteString("\n")
		}
		list := func(head string, ps []*Phrase) {
			if len(ps) == 0 {
				return
			}
			empty = false
			b.WriteString(head + "\n\n")
			for _, ph := range ps {
				fmt.Fprintf(&b, "- `%s`", ph.Pattern)
				if d := strings.TrimPrefix(strings.TrimPrefix(ph.Doc, "Node event: "), "Trace event: "); d != "" {
					b.WriteString(": " + d)
				}
				b.WriteString("\n")
			}
			b.WriteString("\n")
		}
		list("Node event:", nodeEv)
		list("Trace events:", traceEv)
		if p.Activates {
			empty = false
			fmt.Fprintf(&b, "Importing it activates %d observers and %d invariants.\n\n", p.Observers, p.Invariants)
		}
		if empty {
			b.WriteString("No exported phrases.\n\n")
		}
	}
	return strings.TrimRight(strings.ReplaceAll(b.String(), "\n\n\n", "\n\n"), "\n") + "\n"
}

func cell(s string) string { return strings.ReplaceAll(s, "|", `\|`) }

// headOf returns the head of a phrase without its qualifier.
func headOf(ph *Phrase) string {
	h := ph.Items[0].Word
	if i := strings.LastIndexByte(h, '.'); i >= 0 {
		h = h[i+1:]
	}
	return h
}

// Contexts returns the contexts of a std phrase as a set.
func (ph *Phrase) ContextSet() stdlib.Ctx { return ph.ctx }
